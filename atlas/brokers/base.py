"""The execution service owns policy; adapters implement a narrow contract."""

from decimal import Decimal
from typing import Protocol

from atlas.domain import AccountSnapshot, BrokerCapabilities, OrderRequest, OrderResult, Quote


class BrokerAdapter(Protocol):
    capabilities: BrokerCapabilities

    def get_account(self) -> AccountSnapshot: ...
    def get_quote(self, symbol: str, quantity: Decimal = Decimal("1"), side: str = "buy") -> Quote: ...
    def get_open_orders(self) -> tuple[OrderResult, ...]: ...
    def submit_order(self, order: OrderRequest) -> OrderResult: ...
    def cancel_order(self, broker_order_id: str) -> OrderResult: ...
    def get_order_status(self, broker_order_id: str | None = None,
                         client_order_id: str | None = None) -> OrderResult | None: ...
